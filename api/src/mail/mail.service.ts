import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { OnEvent } from '@nestjs/event-emitter';
import nodemailer, { Transporter } from 'nodemailer'; // Импортировали тип Transporter
import type { SendMailOptions } from 'nodemailer/lib/mailer/index.js';
import { PassThrough } from 'stream';
import { PinoLogger } from 'nestjs-pino';
import { ListingPublishedEvent } from '../listings/events/listing-published.event.js';
import { PrismaService } from '../prisma/prisma.service.js';
import { ExternalServiceError } from '../errors/app.exception.js';
import { escapeHtml } from '../common/escapeHtml.service.js';
import { PdfService } from '../pdf/pdf.service.js';

type MailOptions = SendMailOptions;

export type UserMailPayload = {
  email: string;
  name: string;
  [key: string]: unknown;
};

export type ListingMailPayload = {
  id: number;
  title: string;
  price: number | string;
  area: number | string;
  address: string;
  description?: string | null;
  agent?: UserMailPayload;
  [key: string]: unknown;
};

export type ViewingMailPayload = {
  clientName: string;
  clientPhone: string;
  clientEmail: string;
  preferredAt: string | Date;
  listing?: ListingMailPayload;
  [key: string]: unknown;
};

export type DigestStatusChange = {
  listing: { id: number; title: string };
  fromStatus: string;
  toStatus: string;
};

@Injectable()
export class MailService {
  private transporter: Transporter;

  constructor(
    private readonly configService: ConfigService,
    private readonly prisma: PrismaService,
    private readonly pdfService: PdfService,
    private readonly logger: PinoLogger,
  ) {
    const transportType =
      this.configService.get<string>('MAIL_TRANSPORT') ?? 'stream';

    if (transportType === 'real') {
      this.transporter = nodemailer.createTransport({
        host: this.configService.get<string>('SMTP_HOST'),
        port: Number(this.configService.get<number>('SMTP_PORT') ?? 587),
        secure: false,
        auth: {
          user: this.configService.get<string>('SMTP_USER'),
          pass: this.configService.get<string>('SMTP_PASS'),
        },
        connectionTimeout: 5000,
        socketTimeout: 5000,
      });
    } else if (transportType === 'stream') {
      this.transporter = nodemailer.createTransport({
        streamTransport: true,
        buffer: true,
      }) as unknown as Transporter;
    } else {
      this.transporter = {
        sendMail: async (options: MailOptions) => ({
          messageId: 'mocked',
          envelope: options,
        }),
      } as unknown as Transporter;
    }
  }

  async renderListingCardBuffer(listing: ListingMailPayload): Promise<Buffer> {
    const stream = new PassThrough();
    const chunks: Buffer[] = [];
    stream.on('data', (chunk: Buffer) => chunks.push(chunk));

    const done = new Promise<void>((resolve, reject) => {
      stream.on('end', resolve);
      stream.on('error', reject);
    });

    this.pdfService.streamListingCard(stream, listing);
    await done;

    return Buffer.concat(chunks);
  }

  async sendMailSafely(options: MailOptions): Promise<unknown> {
    try {
      const from =
        this.configService.get<string>('MAIL_FROM') ??
        'no-reply@realty-board.local';
      return await this.transporter.sendMail({ from, ...options });
    } catch (err) {
      throw new ExternalServiceError('Failed to send email', [
        err instanceof Error ? err.message : 'Unknown error',
      ]);
    }
  }

  @OnEvent(ListingPublishedEvent.eventName)
  async handleListingPublishedMail(event: ListingPublishedEvent) {
    const agent = await this.prisma.users.findUnique({
      where: { id: event.agentId },
    });
    if (!agent || !agent.email) return;

    const info = (await this.sendMailSafely({
      to: agent.email,
      subject: `Ваше объявление "${event.title}" успешно опубликовано!`,
      text: `Здравствуйте, ${agent.name}! Объявление #${event.listingId} успешно опубликовано.`,
      html: `<h1>${escapeHtml(event.title)}</h1><p>Здравствуйте, ${escapeHtml(agent.name)}! Объявление #${event.listingId} успешно опубликовано.</p>`,
    })) as Record<string, unknown> | null;

    const transportType =
      this.configService.get<string>('MAIL_TRANSPORT') ?? 'stream';
    if (transportType === 'stream' && info?.message) {
      this.logger.info({ transportType }, `Mail generated by stream transport`);
    }
  }

  async sendNewViewingNotice(
    listing: ListingMailPayload,
    viewing: ViewingMailPayload,
  ): Promise<unknown> {
    if (!listing.agent)
      throw new ExternalServiceError('Listing agent is not loaded');
    const pdfBuffer = await this.renderListingCardBuffer(listing);

    return this.sendMailSafely({
      to: listing.agent.email,
      subject: `Новая заявка на просмотр: "${listing.title}"`,
      text: `${viewing.clientName} (${viewing.clientPhone}) хочет посмотреть объявление ${viewing.preferredAt}.`,
      html: `<h1>${escapeHtml(listing.title)}</h1> <p>${escapeHtml(viewing.clientName)} (${escapeHtml(viewing.clientPhone)}) хочет посмотреть объявление ${escapeHtml(viewing.preferredAt)}.</p>`,
      attachments: [
        { filename: `listing-${listing.id}.pdf`, content: pdfBuffer },
      ],
    });
  }

  async sendListingExpiredNotice(
    agent: UserMailPayload,
    listingId: number,
    title: string,
  ): Promise<unknown> {
    return this.sendMailSafely({
      to: agent.email,
      subject: `Объявление "${title}" снято с публикации`,
      text: `Здравствуйте, ${agent.name}! Объявление #${listingId} автоматически снято с публикации, так как прошло 60 дней с момента публикации.`,
      html: `<h1>${escapeHtml(title)}</h1><p>Здравствуйте, ${escapeHtml(agent.name)}! Объявление #${listingId} автоматически снято с публикации, так как прошло 60 дней с момента публикации.</p>`,
    });
  }

  async sendViewingConfirmation(
    listing: ListingMailPayload,
    viewing: ViewingMailPayload,
  ): Promise<unknown> {
    return this.sendMailSafely({
      to: viewing.clientEmail,
      subject: 'Просмотр подтверждён',
      text: `Ваш просмотр объявления "${listing.title}" подтверждён на ${viewing.preferredAt}.`,
      html: `<h1>${escapeHtml(listing.title)}</h1> <p>Ваш просмотр подтверждён на ${escapeHtml(viewing.preferredAt)}.</p>`,
    });
  }

  async sendViewingReminder(viewing: ViewingMailPayload): Promise<unknown> {
    if (!viewing.listing)
      throw new ExternalServiceError('Viewing listing is not loaded');

    return this.sendMailSafely({
      to: viewing.clientEmail,
      subject: `Напоминание о просмотре: "${viewing.listing.title}"`,
      text: `Напоминаем, что ваш просмотр объявления "${viewing.listing.title}" запланирован на ${viewing.preferredAt}.`,
      html: `<h1>${escapeHtml(viewing.listing.title)}</h1><p>Напоминаем, что ваш просмотр запланирован на ${escapeHtml(viewing.preferredAt)}.</p>`,
    });
  }

  async sendAgentDigest(
    agent: UserMailPayload,
    period: { from: Date; to: Date },
    viewings: ViewingMailPayload[],
    statusChanges: DigestStatusChange[],
  ): Promise<unknown> {
    const viewingText = viewings.map(
      (viewing) =>
        `- Объявление #${viewing.listing?.id ?? 0} "${viewing.listing?.title ?? ''}": заявка от ${viewing.clientName} (${viewing.clientPhone}), желаемое время ${viewing.preferredAt.toString()}`,
    );
    const statusText = statusChanges.map(
      (change) =>
        `- Объявление #${change.listing.id} "${change.listing.title}": ${change.fromStatus} → ${change.toStatus}`,
    );
    const viewingHtml = viewings
      .map(
        (viewing) =>
          `<li>Объявление #${viewing.listing?.id ?? 0} "${escapeHtml(viewing.listing?.title ?? '')}": заявка от ${escapeHtml(viewing.clientName)} (${escapeHtml(viewing.clientPhone)}), желаемое время ${escapeHtml(viewing.preferredAt.toString())}</li>`,
      )
      .join('');
    const statusHtml = statusChanges
      .map(
        (change) =>
          `<li>Объявление #${change.listing.id} "${escapeHtml(change.listing.title)}": ${escapeHtml(change.fromStatus)} → ${escapeHtml(change.toStatus)}</li>`,
      )
      .join('');

    const textSections = [
      `Здравствуйте, ${agent.name}!`,
      `Дайджест за период ${period.from.toISOString()} — ${period.to.toISOString()}.`,
      '',
      viewings.length > 0
        ? `Новые заявки на просмотр:\n${viewingText.join('\n')}`
        : '',
      '',
      statusChanges.length > 0
        ? `Изменения статусов:\n${statusText.join('\n')}`
        : '',
    ].filter(Boolean);

    return this.sendMailSafely({
      to: agent.email,
      subject: 'Ежедневный дайджест по объявлениям',
      text: textSections.join('\n'),
      html: `
        <h1>Ежедневный дайджест</h1>
        <p>Здравствуйте, ${escapeHtml(agent.name)}!</p>
        <p>Период: ${escapeHtml(period.from.toISOString())} — ${escapeHtml(period.to.toISOString())}</p>
        ${viewings.length > 0 ? `<h2>Новые заявки на просмотр</h2><ul>${viewingHtml}</ul>` : ''}
        ${statusChanges.length > 0 ? `<h2>Изменения статусов</h2><ul>${statusHtml}</ul>` : ''}
      `,
    });
  }
}
